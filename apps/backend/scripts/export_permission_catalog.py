"""
导出权限码目录：生成前端 / admin 权限码类型，检查生成文件是否最新，报告疑似死码。

Usage:
    uv run python scripts/export_permission_catalog.py                 # 写入生成文件
    uv run python scripts/export_permission_catalog.py --check         # 生成文件过期时退出码为 1
    uv run python scripts/export_permission_catalog.py --report-unused # 打印疑似死码，退出码恒为 0

Author : Coke
Date   : 2026-10-17
"""

import argparse
import re
import sys
from collections.abc import Iterable
from pathlib import Path

BACKEND_ROOT = Path(__file__).resolve().parents[1]
REPO_ROOT = BACKEND_ROOT.parents[1]
sys.path.insert(0, str(BACKEND_ROOT))

from src._menu_seeds import build_menus  # noqa: E402
from src._permission_catalog import load_static_catalog  # noqa: E402

FRONTEND_TYPES = REPO_ROOT / "apps/frontend/src/typings/permission-codes.d.ts"
ADMIN_TYPES = REPO_ROOT / "apps/admin/src/typings/permission-codes.ts"
SOURCE_DIRS = (REPO_ROOT / "apps/frontend/src", REPO_ROOT / "apps/admin/src")
SOURCE_SUFFIXES = {".ts", ".tsx", ".vue"}
HEADER = "/* Auto-generated by apps/backend/scripts/export_permission_catalog.py. Do not edit manually. */"
CODE_LITERAL = re.compile(r"[\"']([a-z][a-z0-9-]*:[a-z][a-z0-9-]*)[\"']")


def render_frontend_types(codes: list[str]) -> str:
    """Global ambient union used by `hasAuth` in apps/frontend."""
    members = "\n".join(f'  | "{code}"' for code in codes)
    return (
        f"{HEADER}\n\n/** Baseline permission codes declared by backend plugins. */\ntype PermissionCode =\n{members}\n"
    )


def render_admin_types(codes: list[str]) -> str:
    """Module exports used by `hasPermission` / `Can` in apps/admin."""
    items = "\n".join(f'  "{code}",' for code in codes)
    return (
        f"{HEADER}\n\n/** Baseline permission codes declared by backend plugins. */\n"
        f"export const PERMISSION_CODES = [\n{items}\n] as const\n\n"
        "export type PermissionCode = (typeof PERMISSION_CODES)[number]\n"
    )


def find_referenced_codes(codes: set[str], source_dirs: Iterable[Path] = SOURCE_DIRS) -> set[str]:
    """Codes appearing as string literals in frontend sources (generated files excluded)."""
    generated = {FRONTEND_TYPES, ADMIN_TYPES}
    referenced: set[str] = set()
    for root in source_dirs:
        for path in root.rglob("*"):
            if path.suffix not in SOURCE_SUFFIXES or path in generated or "node_modules" in path.parts:
                continue
            referenced.update(code for code in CODE_LITERAL.findall(path.read_text(encoding="utf-8")) if code in codes)
    return referenced


def find_unused_codes(codes: Iterable[str], bound: set[str], referenced: set[str]) -> list[str]:
    """Codes with no route binding and no reference anywhere."""
    return sorted(set(codes) - bound - referenced)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail when generated files are stale")
    mode.add_argument("--report-unused", action="store_true", help="print codes without binding or reference")
    args = parser.parse_args(argv)

    catalog, bindings = load_static_catalog()
    codes = sorted(code for code, item in catalog.codes.items() if item.source == "code")

    if args.report_unused:
        menu_codes = {menu.permission for menu in build_menus() if menu.permission}
        referenced = find_referenced_codes(set(codes)) | menu_codes
        for code in find_unused_codes(codes, set(bindings.values()), referenced):
            print(f"WARNING unused permission code (no route binding, no frontend reference): {code}")
        return 0

    outputs = {FRONTEND_TYPES: render_frontend_types(codes), ADMIN_TYPES: render_admin_types(codes)}
    if args.check:
        stale = [
            path
            for path, content in outputs.items()
            if not path.exists() or path.read_text(encoding="utf-8") != content
        ]
        for path in stale:
            print(f"Stale generated file: {path.relative_to(REPO_ROOT)}")
        if stale:
            print("Run: pnpm gen:permission-codes")
            return 1
        return 0

    for path, content in outputs.items():
        path.write_text(content, encoding="utf-8")
        print(f"Generated {path.relative_to(REPO_ROOT)} ({len(codes)} codes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
