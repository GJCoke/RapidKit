# apps/backend/scripts/gen_i18n_types.py
"""
生成 src/locales/types.py（与 src/locales/watch.py 的生成逻辑一致，用于不启动监听时手动生成）。

Usage:
    uv run python scripts/gen_i18n_types.py

Author : Coke
Date   : 2026-10-19
"""

import json
import sys
from pathlib import Path

BACKEND_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND_ROOT))

from src.locales.utils import (  # noqa: E402
    gen_literal_from_dict,
    load_and_flatten_locales,
    load_language_namespace,
    write_py_file,
)

LOCALES_DIR = BACKEND_ROOT / "src" / "locales"


def main() -> None:
    lang_path = str(LOCALES_DIR / "langs")
    locales_data = load_and_flatten_locales(lang_path)
    namespaces = load_language_namespace(lang_path)
    language_literals = ", ".join(json.dumps(ns, ensure_ascii=False) for ns in sorted(namespaces))
    languages_literal_type = f"Literal[{language_literals}]"
    languages_set = f"{{{language_literals}}}" if namespaces else "set()"
    generated_code = "# Auto-generated by gen-i18n-types. Do not edit manually.\n\n"
    generated_code += "from typing import Literal, TypeAlias\n\n"
    generated_code += f"LANGUAGE_TYPE: TypeAlias = {languages_literal_type}\n\n"
    generated_code += f"languages: set[LANGUAGE_TYPE] = {languages_set}\n\n"
    generated_code += gen_literal_from_dict(locales_data["zh-CN"])
    generated_code += "\n"
    write_py_file(str(LOCALES_DIR / "types.py"), generated_code)


if __name__ == "__main__":
    main()
